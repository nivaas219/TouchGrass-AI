export async function recommendMissions({
  mood,
  time,
  energy = "medium",
}) {
  const availableTime = Number(time);

  const candidates = missions.filter(
    (mission) => mission.minTime <= availableTime
  );

  if (!candidates.length) {
    return {
      source: "fallback",
      message: "Try a short outdoor break when you have a little more time.",
      missions: missions.slice(0, 2),
    };
  }

  try {
    const classifier = await getClassifier();

    const labels = candidates.map(
      (mission) => `${mission.title}. ${mission.description}`
    );

    const result = await classifier(
      `The user feels ${mood}, has ${availableTime} minutes, and has ${energy} energy. Recommend an outdoor activity suitable for this situation.`,
      labels,
      { multi_label: false }
    );

    const ranked = result.labels
      .map((label, index) => ({
        ...candidates[labels.indexOf(label)],
        score: result.scores[index],
      }))
      .filter((mission) => mission.title);

    return {
      source: "ai",
      message: "Recommendations generated by an on-device AI model.",
      missions: ranked.slice(0, 3),
    };
  } catch (error) {
    console.error("AI recommendation failed:", error);

    const ranked = candidates
      .map((mission) => ({
        ...mission,
        score:
          (mission.mood.includes(mood) ? 2 : 0) +
          (mission.energy === energy ? 1 : 0),
      }))
      .sort((a, b) => b.score - a.score);

    return {
      source: "fallback",
      message:
        "AI is currently unavailable. Showing mood-based recommendations instead.",
      missions: ranked.slice(0, 3),
    };
  }
}
